import { randomUUID } from "node:crypto";
import request from "supertest";
import { beforeAll, afterAll, afterEach, expect, test, vi } from "vitest";
import { testDatabase } from "./database.js";
import { migrate } from "../src/migrate.js";
import { seedOwner } from "../src/seed.js";
import { createApp } from "../src/app.js";
import { readConfig } from "../src/config.js";
import { importPublicDataset } from "../src/research-dataset.js";
import type { QueryResultRow } from 'pg';

let f: Awaited<ReturnType<typeof testDatabase>>,
  app: ReturnType<typeof createApp>,
  cookie: string;
const datasetId = randomUUID(),
  productId = randomUUID(),
  origin = "http://localhost:3001";
const daily = [
  ...Array.from({ length: 31 }, (_, i) => ({
    date: "2025-08-" + String(i + 1).padStart(2, "0"),
    product_id: productId,
    outlet_id: "A",
    qty: 10,
    quality: "observed",
  })),
  {
    date: "2025-09-01",
    product_id: productId,
    outlet_id: "A",
    qty: 999,
    quality: "observed",
  },
  {
    date: "2025-09-03",
    product_id: productId,
    outlet_id: "A",
    qty: 0,
    quality: "inferred_zero",
  },
];
const payload = {
  format: "coffee-public-dataset-v1",
  id: datasetId,
  data_mode: "PUBLIC_DATASET",
  name: "Test-only generated ETL fixture",
  version: "test",
  content_sha256: "e".repeat(64),
  source_url: "https://example.com/test",
  license: "Test fixture",
  license_url: "https://example.com/license",
  attribution: "Generated by automated tests",
  transform_version: "fixture-v1",
  products: [
    { id: productId, name: "External test product", external_id: "1" },
  ],
  outlets: [{ id: "A", date_from: "2025-08-01", date_to: "2025-09-30" }],
  report: { item_occurrences: 1309 },
  daily,
};

beforeAll(async () => {
  f = await testDatabase();
  await migrate(f.db);
  await seedOwner(f.db, "owner@example.com", "Test-only-password-123");
  app = createApp(
    f.db,
    readConfig({ DATABASE_URL: "postgresql://test:test@localhost/test" }),
  );
  const login = await request(app)
    .post("/api/auth/login")
    .set("Origin", origin)
    .send({ email: "owner@example.com", password: "Test-only-password-123" })
    .expect(200);
  cookie = login.headers["set-cookie"]![0]!.split(";")[0]!;
  await f.db.query(
    "INSERT INTO ingredients(id,name,unit,current_stock,reorder_point,cost_satang) VALUES($1,'Unrelated operational milk','ml',111,0,1)",
    [randomUUID()],
  );
}, 30000);
afterEach(() => vi.restoreAllMocks());
afterAll(async () => f?.close());
test("research import is idempotent, immutable, reconciled and isolated from live products", async () => {
  expect(await importPublicDataset(f.db, payload)).toMatchObject({
    imported: true,
    rows: 33,
  });
  expect(await importPublicDataset(f.db, payload)).toMatchObject({
    imported: false,
    rows: 33,
  });
  expect((await f.db.query("SELECT id FROM products")).rows).toHaveLength(0);
  expect(
    (await f.db.query("SELECT product_id FROM research_daily_demand")).rows,
  ).toHaveLength(33);
  await expect(
    f.db.query("UPDATE research_daily_demand SET qty=0 WHERE dataset_id=$1", [
      datasetId,
    ]),
  ).rejects.toThrow();
  await expect(
    f.db.query("DELETE FROM research_datasets WHERE id=$1", [datasetId]),
  ).rejects.toThrow();
  await expect(
    importPublicDataset(f.db, { ...payload, daily: [...daily, daily[0]] }),
  ).rejects.toThrow();
});

test("public replay has exclusive cutoff, immutable predictions before truth reads, honest metrics and no POS writes", async () => {
  let fetched = false;
  const query = vi.spyOn(f.db, "query");
  const transaction=f.db.transaction.bind(f.db);
  vi.spyOn(f.db,'transaction').mockImplementation(work=>transaction(sql=>work({
    async query<T extends QueryResultRow>(text:string,values?:unknown[]){
      query.mock.calls.push([text,values]);
      if(text.includes('date >= $3::date AND date <')){
        const archived=await sql.query('SELECT count(*)::int AS n FROM research_replay_points');
        expect(archived.rows[0]?.n).toBeGreaterThan(0);
      }
      return sql.query<T>(text,values);
    },
  })));
  vi.spyOn(globalThis, "fetch").mockImplementation(async (_url, options) => {
    const body = JSON.parse(options!.body as string);
    expect(body.cohort).toBe("public_dataset");
    expect(body.history).toHaveLength(31);
    expect(
      body.history.every(
        (r: { date: string; qty: number; unit_price: number }) =>
          r.date < "2025-09-01" && r.qty === 10 && r.unit_price === 0,
      ),
    ).toBe(true);
    expect(
      query.mock.calls.some(([sql]) =>
        sql.includes("date >= $3::date AND date <"),
      ),
    ).toBe(false);
    fetched = true;
    return new Response(
      JSON.stringify(
        Array.from({ length: 7 }, (_, i) => ({
          date: "2025-09-0" + (i + 1),
          product_id: productId,
          predicted_qty: 10,
          lower: null,
          upper: null,
          history_source: "actual",
          model_version: "mean-7-v1",
          diagnostics: {
            origin: "2025-08-31",
            history_days: 31,
            reason: "limited_history_mean",
            selection: {},
            pipeline: "coffee-demand-v5",
            training_cohort: "public_dataset",
          },
        })),
      ),
      { status: 200 },
    );
  });
  const response = await request(app)
    .post("/api/forecasts/backtest")
    .set("Origin", origin)
    .set("Cookie", cookie)
    .send({
      dataset_id: datasetId,
      outlet_id: "A",
      cutoff: "2025-09-01",
      horizon: 7,
    })
    .expect(200);
  expect(fetched).toBe(true);
  expect(response.body.run.cutoff).toBe("2025-09-01");
  expect(response.body.run.metadata.training_to).toBe("2025-08-31");
  expect(response.body.score).toMatchObject({
    samples: 2,
    mae: 499.5,
    wape: 100,
    bias: -489.5,
  });
  expect(response.body.coverage).toMatchObject({
    expected: 7,
    matched: 2,
    missing: 5,
    inferred_zero: 1,
  });
  expect(response.body.rows[1].actual_qty).toBeNull();
  expect(response.body.rows[2].actual_qty).toBe(0);
  const id = response.body.run.id;
  const saved = await request(app)
    .get("/api/forecasts/replays/" + id)
    .set("Cookie", cookie)
    .expect(200);
  expect(saved.body.rows).toEqual(response.body.rows);
  expect(new Date(response.body.run.created_at).getTime()).toBeGreaterThan(
    Date.parse("2026-01-01"),
  );
  // Assert the held-out SQL only executed once the saved run was readable.
  const actualCalls = query.mock.calls.filter(([sql]) =>
    sql.includes("date >= $3::date AND date <"),
  );
  expect(actualCalls.length).toBeGreaterThan(0);
  await expect(
    f.db.query(
      "UPDATE research_replay_points SET prediction=$1 WHERE run_id=$2",
      ["{}", id],
    ),
  ).rejects.toThrow();
  expect((await f.db.query("SELECT id FROM orders")).rows).toHaveLength(0);
  expect((await f.db.query("SELECT id FROM forecast_runs")).rows).toHaveLength(
    0,
  );
  expect((await f.db.query("SELECT id FROM forecasts")).rows).toHaveLength(0);
  expect(
    Number(
      (await f.db.query("SELECT current_stock FROM ingredients")).rows[0]!
        .current_stock,
    ),
  ).toBe(111);
});

